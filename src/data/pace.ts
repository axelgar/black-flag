// The tempo of the sea. Every ship's speed and way-making, every ball in flight and the
// squadrons' search are the numbers in their tables times PACE — so the tables stay
// comparable with each other (and with v1's), a faster game keeps the same fights (who
// out-sails whom, how far a ball leads its mark), and how fast it plays is one number.
// The helm quickens a little with it, so a faster ship still turns tight enough to work
// round an island.
export const PACE = 1.25;
export const HELM = 1.1;
